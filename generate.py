#!/usr/bin/env python3
"""Generate the terminal themes from palette/{night,light}.toml.

    python3 generate.py           write terminal/ghostty/* and terminal/foot/theme.ini
    python3 generate.py --check   exit 1 if the files on disk differ

The Kakoune colourschemes and the Giallo themes are hand-authored (a theme is
more than a palette), and tests/test_parity.py enforces that every colour they
share with the palette matches it exactly. Everything the terminal needs is
generated, because a terminal theme is nothing but the palette in another syntax.
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PALETTE = ROOT / "palette"
GHOSTTY = ROOT / "terminal" / "ghostty"
FOOT = ROOT / "terminal" / "foot"

VARIANTS = {
    "night": {"ghostty": "Tomorrow Night", "foot_section": "[colors-dark]",
              "kind": "dark"},
    "light": {"ghostty": "Tomorrow", "foot_section": "[colors-light]",
              "kind": "light"},
}

# Foot-only, not palette: translucency is a per-machine taste, and
# initial-color-theme lives in foot.ini because darkman writes state.ini.
FOOT_ALPHA = "0.95"

GHOSTTY_HEADER = """\
# {label} -- generated by generate.py from palette/{name}.toml. Do not edit.
# Managed by chezmoi; the filename shadows the built-in theme of the same name,
# so if the sync is missing Ghostty falls back to the stock palette.
#
# Slot 8 is the theme's comment colour rather than the stock near-black, which
# is only 1.9:1 on the background and is what zsh-autosuggestions and fzf paint
# dim text with. Foot uses the same value.
"""

FOOT_HEADER = """\
# Foot colour themes: Beautiful Tomorrow (dark) / (light) -- generated by
# generate.py from palette/. Do not edit.
# Matches Ghostty: theme = light:Tomorrow,dark:Tomorrow Night
#
# Slot 8 is the theme's comment colour: zsh-autosuggestions paints suggestions
# with SGR 90 and fzf's dim bits use it too, and the stock near-black is only
# 1.9:1 on the background.
#
# initial-color-theme lives in foot.ini (not here); darkman writes it to
# state.ini and signals running instances (SIGUSR1=dark, SIGUSR2=light), so live
# windows follow the mode too.
"""


def load(name):
    with open(PALETTE / f"{name}.toml", "rb") as f:
        return tomllib.load(f)


def ghostty(name, p, cfg):
    if cfg["kind"] == "dark":
        label = "Tomorrow Night (dark)"
    else:
        label = "Tomorrow (light)"
    lines = [GHOSTTY_HEADER.format(label=label, name=name)]
    for slot in range(16):
        lines.append(f"palette = {slot} = #{p['ansi'][str(slot)]}")
    lines += [
        f"background = #{p['background']}",
        f"foreground = #{p['foreground']}",
        f"cursor-color = #{p['cursor']}",
        f"cursor-text = #{p['cursor_text']}",
        f"selection-background = #{p['selection']}",
        f"selection-foreground = #{p['foreground']}",
    ]
    return "\n".join(lines) + "\n"


def foot_section(name, p, cfg):
    lines = [cfg["foot_section"],
             "# Translucent background, 0.0 = fully transparent, 1.0 = opaque.",
             f"alpha = {FOOT_ALPHA}",
             f"foreground = {p['foreground']}",
             f"background = {p['background']}",
             "# foot's order is \"<text> <cursor-block>\", the reverse of Ghostty's",
             "# cursor-colour/cursor-text pair.",
             f"cursor = {p['background']} {p['foreground']}",
             ""]
    for slot in range(8):
        lines.append(f"regular{slot} = {p['ansi'][str(slot)]}")
    lines.append("")
    for slot in range(8):
        lines.append(f"bright{slot} = {p['ansi'][str(slot + 8)]}")
    return "\n".join(lines)


def foot(name, p, cfg):
    return foot_section(name, p, cfg) + "\n"


def artifacts():
    """Every generated file, as {path: contents}."""
    out = {}
    foot_parts = [FOOT_HEADER]
    for name, cfg in VARIANTS.items():
        p = load(name)
        out[GHOSTTY / cfg["ghostty"]] = ghostty(name, p, cfg)
        foot_parts.append(foot_section(name, p, cfg))
    out[FOOT / "theme.ini"] = "\n".join(foot_parts) + "\n"
    return out


def main(argv):
    generated = artifacts()
    check = "--check" in argv
    stale = []
    for path, contents in generated.items():
        if check:
            if not path.exists() or path.read_text() != contents:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: python3 generate.py", file=sys.stderr)
            return 1
        print(f"up to date: {len(generated)} files")
    else:
        for path in generated:
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
